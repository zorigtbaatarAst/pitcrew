#!/usr/bin/env bash
# themes/mono.sh — no hues, only weight. For terminals where the 16-color
# palette clashes with everything else on screen, and for screenshots.
BOLD="$ESC[1m"; DIM="$ESC[2m"; RESET="$ESC[0m"
RED="$ESC[1m"; GREEN="$ESC[0m"; YELLOW="$ESC[2m"; BLUE="$ESC[0m"
MAGENTA="$ESC[1m"; CYAN="$ESC[1m"; GREY="$ESC[2m"
